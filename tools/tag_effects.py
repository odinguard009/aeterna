#!/usr/bin/env python3
"""Effect glossary tagger (each entry also carries the official rule it follows in "rule").
  python3 tools/tag_effects.py              -> writes data/glossary/card-tags.json and docs/reports/effect-coverage.md
Scans the English card text of build/all-cards.json with the patterns of data/glossary/effects.json.
Each card gets the tags it uses; the report shows, per tag, how many cards use it and whether the engine can do it,
and lists the cards that still need a missing/partial piece (sorted by how many tags are missing).
Patterns are hints for a human/Claude, not a parser: always read the card text before wiring."""
import json, re, os, collections
import allcards      # build/all-cards.json is generated (not in git): allcards.load() writes it when missing or stale
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
gl = json.load(open(os.path.join(root, 'data/glossary/effects.json'), encoding='utf-8'))
cards = allcards.load()
rx = [(g, re.compile(g['pattern'])) for g in gl]
tags = {}; use = collections.defaultdict(list)
for c in cards:
    t = [g['id'] for g, r in rx if r.search(c.get('text') or '')]
    tags[c['id']] = t
    for x in t: use[x].append(c['id'])
json.dump(tags, open(os.path.join(root, 'data/glossary/card-tags.json'), 'w', encoding='utf-8'), indent=1)
by = {g['id']: g for g in gl}
L = ['# Effect coverage (generated by tools/tag_effects.py)', '', f'{len(cards)} cards, {len(gl)} glossary entries.', '',
     '| Tag | Kind | Meaning | Engine | Status | Cards |', '|---|---|---|---|---|---|']
for g in gl: L.append(f"| {g['id']} | {g['kind']} | {g['meaning']} | {g['engine']} | {g['status']} | {len(use[g['id']])} |")
L += ['', '## Missing / partial tags by number of cards that need them', '']
need = sorted([(len(use[g['id']]), g) for g in gl if g['status'] != 'wired' and use[g['id']]], key=lambda x: -x[0])
for n, g in need: L.append(f"- **{g['id']}** ({g['status']}, {n} cards): {g['meaning']}. {g.get('example','')}")
L += ['', '## Cards with the most unwired tags', '']
cnt = [(sum(1 for x in tags[c['id']] if by[x]['status'] != 'wired'), c) for c in cards]
for n, c in sorted(cnt, key=lambda x: -x[0])[:15]:
    if n: L.append(f"- {c['id']} {c['name']}: {', '.join(x for x in tags[c['id']] if by[x]['status'] != 'wired')}")
open(os.path.join(root, 'docs/reports/effect-coverage.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('tagged', len(tags), 'cards ->', 'data/glossary/card-tags.json, docs/reports/effect-coverage.md')
