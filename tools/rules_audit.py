#!/usr/bin/env python3
"""Rules audit (v0.55.1, roadmap 'Rules audit' R2): every rule the engine claims is listed with its source and a verdict.
Items: every table row of docs/rules-coverage.md, every glossary `rule` note (data/glossary/effects.json) and every
'house reading / ruling chosen / not covered / unverified' line in docs/manual-notes.md + docs/ai/roadmap-open.md + docs/ai/roadmap-archive.md.
Verdicts: confirmed (official page/section cited) | house (no official text; kept, reason given) | conflict (the source
says otherwise -> an R3 fix) | open (no source cited yet / needs a check). Hand-set verdicts in
docs/rules-audit-verdicts.json win; the rest is classified from the citation words of the item itself.
  python3 tools/rules_audit.py            -> writes docs/reports/rules-audit.md, prints the summary line
  python3 tools/rules_audit.py --line     -> summary line only (used by tools/session_start.sh)"""
import json, re, sys, os, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)
V = json.load(open(P('docs/rules-audit-verdicts.json'), encoding='utf-8'))
CITE = re.compile(r'(Rule Manual|manual|Comprehensive|\bCR\b|FAQ)[^.;|]*?(p\.|pp\.|sec\.|Q\d|\d+-\d+|page)', re.I)
HOUSE = re.compile(r'house reading|ruling chosen|card text|no manual|no (Eternal|official|rule) |not covered|built as printed|Engine:', re.I)

def items():
    sec = ''
    for ln in open(P('docs/rules-coverage.md'), encoding='utf-8'):
        if ln.startswith('#'): sec = ln.strip('# \n'); continue
        if not ln.startswith('|') or ln.startswith('|---') or re.match(r'\|\s*(Area|Format)\s*\|', ln): continue
        if sec in ('Formats', 'Status legend'): continue
        cells = [c.strip() for c in ln.strip().strip('|').split('|')]
        yield ('coverage', sec[:60], cells[0], ' | '.join(cells[1:]), sec)
    for g in json.load(open(P('data/glossary/effects.json'), encoding='utf-8')):
        if g.get('rule'): yield ('glossary', 'data/glossary/effects.json', g['id'], g['rule'], '')
    for f in ('docs/manual-notes.md', 'docs/ai/roadmap-open.md', 'docs/ai/roadmap-archive.md'):
        for i, ln in enumerate(open(P(f), encoding='utf-8'), 1):
            if re.search(r'house reading|ruling chosen|not covered|unverified', ln, re.I) and not ln.startswith('#') and 'rules_audit' not in ln:
                yield ('note', f'{f}:{i}', ln.strip()[:70], ln.strip(), '')

def verdict(kind, key, text, ctx):
    whole = f'{key} {text}'.lower()
    for v in V['items']:
        if re.search(r'(?<!\w)' + re.escape(v['match'].lower()) + r'(?!\w)', whole): v['_used'] = True; return v['verdict'], v['source'], v['note']
    text = f'{key} | {text}'
    if HOUSE.search(text) and not CITE.search(text): return 'house', 'card text / engine reading', 'auto: no official text cited'
    m = CITE.search(text) or (CITE.search(ctx) if ctx else None)
    if m: return 'confirmed', (text if CITE.search(text) else ctx)[max(0, m.start()-10):m.end()+25].strip(), 'auto: source cited'
    if HOUSE.search(text): return 'house', 'card text / engine reading', 'auto'
    return 'open', '', 'no source cited yet'

def main():
    rows = [(k, w, key, t, *verdict(k, key, t, ctx)) for k, w, key, t, ctx in items()]
    n = collections.Counter(r[4] for r in rows)
    line = f"rules audit {V['checked']}: {len(rows)} items, confirmed {n['confirmed']}, house {n['house']}, conflict {n['conflict']}, open {n['open']}"
    if '--line' in sys.argv: print(line); return
    cut = lambda s, k=110: (s[:k] + '...') if len(s) > k else s
    esc = lambda s: s.replace('|', '/').replace('\n', ' ')
    out = ['# Rules audit (generated by `python3 tools/rules_audit.py`; edit verdicts in `docs/rules-audit-verdicts.json`)', '',
           f'**{line}.** Sources and versions: `docs/manual-notes.md` (top table). Verdicts: **confirmed** = official page/section cited; '
           '**house** = no official text, kept; **conflict** = the source says otherwise (R3 fix, one patch each); **open** = no source cited yet.',
           'Auto verdicts trust the citation written next to the rule; a cited English VER.17.0 page can still lag the Japanese 17.1 text.', '']
    for want in ('conflict', 'open', 'house', 'confirmed'):
        part = [r for r in rows if r[4] == want]
        out += [f'## {want.capitalize()} ({len(part)})', '', '| Kind | Where | Item | Source | Note |', '|---|---|---|---|---|']
        out += [f'| {k} | {esc(cut(w, 40))} | {esc(cut(key, 60))} | {esc(cut(src, 90))} | {esc(cut(note or t, 160))} |' for k, w, key, t, _, src, note in part]
        out.append('')
    unused = [v['match'] for v in V['items'] if not v.get('_used')]
    if unused: out += ['## Verdicts that matched nothing', ''] + [f'- {u}' for u in unused] + ['']
    open(P('docs/reports/rules-audit.md'), 'w', encoding='utf-8').write('\n'.join(out))
    print(line + (f'; unused verdicts: {len(unused)}' if unused else ''))

if __name__ == '__main__': main()
