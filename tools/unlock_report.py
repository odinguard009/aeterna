#!/usr/bin/env python3
"""Unlock report (audit 2026-10-16): how many staged cards each piece of work would make playable.
  python3 tools/unlock_report.py          -> writes docs/unlock-report.md and prints one summary line
  python3 tools/unlock_report.py --line   -> prints the summary line only (used by tools/session_start.sh)
It runs the glossary patterns (data/glossary/effects.json) over the English text of every staged card in
data/import and sorts the cards into classes. The patterns are hints, not a parser, so "ready" is an
upper bound: it means "no new engine mechanic seems needed", not "can be promoted without reading".
Use it to order the roadmap by cards unlocked per token, never as proof that a card works."""
import collections, glob, json, os, re, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
J = lambda p: json.load(open(os.path.join(root, p), encoding='utf8'))
gl = J('data/glossary/effects.json')
rx = [(g, re.compile(g['pattern'])) for g in gl]
playable = {c['id'] for c in J('data/cards/all-cards.json')}
staged = [c for f in sorted(glob.glob(os.path.join(root, 'data/import/saga-[0-9][0-9].json')))
          for c in json.load(open(f, encoding='utf8')) if c['id'] not in playable]
total = len(playable) + len(staged)
line = f'playable {len(playable)} / {total:,} cards ({len(staged):,} staged in data/import)'
if '--line' in sys.argv: print(line); sys.exit(0)

CLASSES = ['vanilla', 'ready', 'partly tagged', 'blocked', 'unknown text']
cls = collections.Counter(); per_saga = collections.defaultdict(collections.Counter)
single = collections.Counter(); anyb = collections.Counter(); pair = collections.Counter()
for c in staged:
    t = (c.get('text') or '').strip()
    tags = [g for g, r in rx if r.search(t)]
    bad = sorted({g['id'] for g in tags if g['status'] != 'wired'})
    sentences = [s for s in re.split(r'[\n.]', t) if len(s.strip()) > 12]
    if not t: k = 'vanilla'
    elif not tags: k = 'unknown text'
    elif bad: k = 'blocked'
    elif len(tags) >= 0.6 * len(sentences): k = 'ready'
    else: k = 'partly tagged'
    cls[k] += 1; per_saga[str(c.get('saga') or '?')][k] += 1
    for b in bad: anyb[b] += 1
    if len(bad) == 1: single[bad[0]] += 1
    if len(bad) == 2: pair[' + '.join(bad)] += 1

by = {g['id']: g for g in gl}
L = ['# Unlock report (generated by tools/unlock_report.py; do not edit)', '',
     f'**{line}.** Estimate from glossary patterns: "ready" is an upper bound (no new mechanic seems needed; '
     'every card is still read and wired before promotion).', '',
     '| Class | Cards | Meaning |', '|---|---|---|']
MEAN = {'vanilla': 'no effect text', 'ready': 'only wired tags, most sentences tagged',
        'partly tagged': 'wired tags, but much of the text is not recognised by the glossary',
        'blocked': 'needs at least one partial/missing tag', 'unknown text': 'text, but no glossary tag matches'}
for k in CLASSES: L.append(f'| {k} | {cls[k]:,} | {MEAN[k]} |')
L += ['', '## Work order: tags that are the only blocker (cards unlocked when that tag is finished)', '',
      '| Tag | Status | Only blocker | Blocks in total | Meaning |', '|---|---|---|---|---|']
for tag, n in single.most_common(15):
    g = by[tag]; L.append(f"| {tag} | {g['status']} | {n} | {anyb[tag]} | {g['meaning'][:80]} |")
NOTES = {'K_ULTIMATE': 'the pattern matches any text that mentions Ultimates, mostly "Spirit/Ultimate" targets on Spirit and Magic cards; '
                        'so the first step is target selectors that accept Ultimates, then the Ultimate-card leftovers',
         'K_BRAVE': 'the pattern matches any mention of Brave (Brave cards and Spirits that refer to braved Spirits)'}
L += [''] + [f'- {t}: {n}.' for t, n in NOTES.items() if t in single]
L += ['', '## Pairs of blockers (cards unlocked when both are finished)', '']
L += [f'- {p}: {n}' for p, n in pair.most_common(8)]
L += ['', '## Per Saga (staged cards)', '', '| Saga | ' + ' | '.join(CLASSES) + ' |', '|---' * (len(CLASSES) + 1) + '|']
for s in sorted(per_saga, key=lambda x: int(x) if x.isdigit() else 99):
    L.append(f'| {s} | ' + ' | '.join(str(per_saga[s][k]) for k in CLASSES) + ' |')
open(os.path.join(root, 'docs/unlock-report.md'), 'w', encoding='utf8').write('\n'.join(L) + '\n')
print(line, '->', 'docs/unlock-report.md')
