#!/usr/bin/env node
// Packs the project into ONE Markdown file for an AI chat (the Repomix role), e.g. the brainstorming chat.
//   node tools/pack_ai.mjs            -> build/aeterna-pack.md  (rules docs + source, card data summarised)
//   node tools/pack_ai.mjs --full     -> also the full card JSON
//   node tools/pack_ai.mjs --docs     -> docs only (cheapest: for idea / rules discussions without code)
// Prints the size and a rough token estimate (characters / 4).
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SRC_DIRS } from './src_parts.mjs';
import { ensureAllCards } from './all_cards.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const full = process.argv.includes('--full'), docsOnly = process.argv.includes('--docs');
const rd = p => readFileSync(join(ROOT, p), 'utf8');
const ls = (d, rx) => existsSync(join(ROOT, d)) ? readdirSync(join(ROOT, d)).filter(f => rx.test(f)).sort().map(f => d + '/' + f) : [];
const fence = (p, lang) => `\n## ${p}\n\n\`\`\`\`${lang}\n${rd(p).replace(/\n$/, '')}\n\`\`\`\`\n`;

let out = `# Aeterna: project pack (generated by tools/pack_ai.mjs${full ? ' --full' : docsOnly ? ' --docs' : ''})\n\n` +
  'Read CLAUDE.md first. The shipped game is index.html, built from packages/ and apps/web/ by tools/build.mjs (do not edit index.html by hand).\n';
const files = ['CLAUDE.md', 'README.md', 'CHANGELOG.md', ...ls('docs', /\.md$/)];
for (const f of files) out += fence(f, 'md');
if (!docsOnly) {
  out += fence('apps/web/index.template.html', 'html') + fence('apps/web/styles.css', 'css');
  for (const d of SRC_DIRS) for (const f of ls(d, /\.js$/)) out += fence(f, 'js');
  for (const f of ['tools/build.mjs', ...ls('tests/unit', /\.mjs$/)]) out += fence(f, 'js');
}
ensureAllCards(ROOT);
const cards = JSON.parse(rd('build/all-cards.json'));
if (full) out += fence('build/all-cards.json', 'json');
else out += '\n## Card list (summary of build/all-cards.json)\n\n| id | name | type | colour | cost | Saga |\n|---|---|---|---|---|---|\n' +
  cards.map(c => `| ${c.id} | ${c.name} | ${c.type} | ${c.color} | ${c.cost} | ${c.saga} |`).join('\n') + '\n';

mkdirSync(join(ROOT, 'build'), { recursive: true });
const dest = join(ROOT, 'build', docsOnly ? 'aeterna-docs-pack.md' : 'aeterna-pack.md');
writeFileSync(dest, out);
console.log(`wrote ${dest.replace(ROOT + '/', '')}: ${out.length} chars, ~${Math.round(out.length / 4)} tokens`);
