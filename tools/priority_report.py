#!/usr/bin/env python3
"""Priority report (owner request 2026-10-18): which cards to make playable first.
  python3 tools/priority_report.py          -> writes docs/reports/priority-report.md, prints one line
  python3 tools/priority_report.py --line   -> prints the summary line only
Order (owner, 2026-10-18): newest cards first, by format the game is played in today:
  1. Standard block A (the official format since April 2026; sets 26R*, table STANDARD_SETS below),
  2. Eternal by Saga, newest first (17 = Contract Saga: Proof, BS76-BS77, then 16, 15, ...).
Inside a tier the goal is decks, not totals: every colour should reach DECK_TARGET distinct playable cards
(a 40-card deck holds at most 3 copies of a name, so 14 names make one deck; 40 names give several).
It also lists effect texts shared by several staged cards (one implementation unlocks the group) and the
name suffixes (XV, LT, RV, X) that mark NEW cards, not reprints: they have their own name and text."""
import collections, glob, json, os, re, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
J = lambda p: json.load(open(os.path.join(root, p), encoding='utf8'))
DECK_TARGET = 40
COLOURS = ['red', 'purple', 'green', 'white', 'yellow', 'blue']
# Standard block A sets with their release dates and card numbers on the Fandom set pages
# (read 2026-10-18 through the wiki API in the owner's built-in browser; later sets have no card list yet).
STANDARD_SETS = [
    ('26RSD01-06', '2026-04-11', 115, 'six Entry Decks'), ('26RBS01', '2026-04-18', 144, 'The Genesis Pulse'),
    ('26RSD07', '2026-06-20', 16, 'starter'), ('26RCB01', '2026-06-20', 78, 'collaboration booster'),
    ('26RBS02', '2026-07-18', 111, 'The Illusory Winds'), ('26RDB01', '2026-09-26', 70, 'booster'),
    ('26RSD08', '2026-09-26', 16, 'starter'), ('26RSD09-10', '2026-10-10', 33, 'anime starters'),
    ('26RBS03', '2026-10-17', 117, 'The Ruler of Zekkai')]

playable = {c['id'] for c in J('data/cards/all-cards.json')}
cards = {}
for f in sorted(glob.glob(os.path.join(root, 'data/import/saga-[0-9][0-9].json'))) + \
        sorted(glob.glob(os.path.join(root, 'data/cards/saga-[0-9][0-9].json'))):
    for c in json.load(open(f, encoding='utf8')): cards[c['id']] = c
allc = list(cards.values())
is_std = lambda c: str(c.get('block', '')).upper() == 'A' or c['id'].startswith('26R')
std_in = [c for c in allc if is_std(c)]
std_listed = sum(n for _, _, n, _ in STANDARD_SETS)
line = (f'priority: Standard block A {sum(c["id"] in playable for c in std_in)} playable / {len(std_in)} in data / '
        f'~{std_listed} released; newest Eternal Saga {max(c.get("saga") or 0 for c in allc)}')
if '--line' in sys.argv: print(line); sys.exit(0)

norm = lambda t: re.sub(r'\s+', ' ', re.sub(r'\[\[|\]\]', '', t or '')).strip().lower()
out = ['# Priority report (generated by tools/priority_report.py; do not edit)', '',
       f'**{line}.** Owner, 2026-10-18: newest cards first; inside a tier, whole decks per colour '
       f'(target {DECK_TARGET} distinct playable cards per colour) before totals.', '',
       '## 1. Standard block A (official format since April 2026)', '',
       f'Only {len(std_in)} block A cards are in the card data; the Fandom export in `data/sources` covers BS01-BS77 only. '
       'Block A cards use the Standard wording "Target ... Spirit. Destroy it." (target sentence + action sentence), '
       'which the current compiler does not read (0 of 12 simple samples on 2026-10-18), so the import needs the '
       'two-sentence compiler first (roadmap: compiler v2).', '',
       '| Set | Released | Cards on Fandom | Note |', '|---|---|---|---|']
out += [f'| {s} | {d} | {n} | {t} |' for s, d, n, t in STANDARD_SETS]
out += [f'| total | | ~{std_listed} | card numbers on the set pages (reprints inside starters counted) |', '']

out += ['## 2. Eternal by Saga, newest first', '', '| Saga | Sets | Cards | Playable | % | ' +
        ' | '.join(c.capitalize() for c in COLOURS) + ' |', '|---|---|---|---|---|' + '---|' * len(COLOURS)]
by_saga = collections.defaultdict(list)
for c in allc:
    if not is_std(c): by_saga[c.get('saga') or 0].append(c)
for s in sorted(by_saga, reverse=True):
    L = by_saga[s]; p = [c for c in L if c['id'] in playable]
    sets = sorted({c.get('set') or '' for c in L if (c.get('set') or '').startswith('BS')})
    span = f'{sets[0]}-{sets[-1]}' if sets else '-'
    col = collections.Counter(k for c in p for k in (c.get('colors') or [c.get('color')]))
    out.append(f'| {s} | {span} | {len(L)} | {len(p)} | {100 * len(p) // max(1, len(L))}% | ' +
               ' | '.join(f'{col[k]}' + ('' if col[k] >= DECK_TARGET else '') for k in COLOURS) + ' |')
out += ['', f'Colour columns: distinct playable cards; the deck target is {DECK_TARGET} per colour in the newest Saga.', '']

st = collections.defaultdict(list)
for c in allc:
    if c['id'] not in playable and norm(c.get('text')): st[(c['type'], norm(c['text']))].append(c['id'])
groups = sorted((v for v in st.values() if len(v) > 1), key=len, reverse=True)
out += ['## 3. Shared effect texts (one implementation unlocks the group)', '',
        f'{len(groups)} texts are shared by {sum(map(len, groups))} staged cards. The rest of the pool is close to one '
        'text per card: reprints with the same text are rare (17 exact duplicates in 8,041).', '']
out += [f'- {", ".join(v[:6])}{" ..." if len(v) > 6 else ""}' for v in groups[:25]]

suf = collections.Counter()
for c in allc:
    m = re.search(r' (XV|LT|X|Ω)$', c['name'])
    if m: suf[m.group(1)] += 1
rv = sum(1 for c in allc if '-RV' in c['id'])
out += ['', '## 4. Version marks are new cards, not reprints', '',
        f'Name suffixes: {", ".join(f"{k} {n}" for k, n in suf.most_common())}; card numbers with RV (revival): {rv}. '
        'Each has its own name and rewritten text (for example "Reanimate LT" adds a Main effect to the old Flash), '
        'so each needs its own effects. They are recent cards, so they rank by their Saga like any other card.', '']
open(os.path.join(root, 'docs/reports/priority-report.md'), 'w', encoding='utf8').write('\n'.join(out) + '\n')
print(line)
